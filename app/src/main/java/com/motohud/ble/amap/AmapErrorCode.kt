package com.motohud.ble.amap

/**
 * 高德错误码 → 人话。
 *
 * 这些错误码是用户最容易卡住的地方：同样是"搜不到"，可能是网络、可能是 Key 平台
 * 选错（Web 服务 Key 用在 Android SDK 上）、也可能是 Key 没绑定当前包名/签名。
 * 直接给错误码用户看不懂，所以在这里统一翻译成可执行的建议。
 */
object AmapErrorCode {

    /** 错误码 → 简短原因 */
    fun reason(code: Int): String = when (code) {
        1000 -> "成功"
        1001 -> "Key 不正确或已过期"
        1002 -> "网络异常或请求被拒绝"
        1003 -> "服务返回异常"
        1004 -> "访问过于频繁，请稍后再试"
        1005 -> "IP 访问超限"
        1006 -> "Key 绑定的域名/IP 不匹配"
        1007 -> "Key 不属于当前平台"
        1008 -> "Key 已被删除"
        1009 -> "Key 未开通该服务"
        1010 -> "账号已被禁用"
        1804 -> "起点与终点距离过近"
        1806 -> "起点或终点不在可行区域"
        10001 -> "Key 无效，或与包名/签名不匹配"
        10002 -> "Key 未开通该服务"
        10003 -> "今日调用量已超限"
        10004 -> "单位时间调用过于频繁"
        10005 -> "IP 白名单校验失败"
        10006 -> "签名校验失败"
        10007 -> "Key 绑定的平台不匹配"
        10008 -> "Key 绑定信息缺失"
        10009 -> "Key 的平台类型不匹配（例如把 Web 服务 Key 用在了 Android SDK）"
        10044 -> "账号维度日调用量已超限"
        else -> "未知错误"
    }

    /** 错误码 → 可执行建议 */
    fun advice(code: Int): String = when (code) {
        1002 -> "先确认设备能正常上网；若网络正常，多半是 Key 未绑定当前包名与签名。"
        10001, 10006 -> "到高德控制台核对：Key 类型为「Android 平台」，且包名、签名 SHA1 与本页显示完全一致。"
        10007, 10009, 1009 -> "这个 Key 不是「Android 平台」类型。请在控制台新建一个 Android 平台 Key，或在同一个 Key 上追加 Android 平台。"
        10003, 10044 -> "去控制台查看配额，或等次日额度重置。"
        1806 -> "终点在禁行区域（如步行街、封闭小区），换一个附近的可达点试试。"
        else -> "把错误码截图发出来可以进一步定位。"
    }

    /**
     * 命中 Key/授权类错误（这类错误要引导用户去控制台，而不是让他反复重试）。
     */
    fun isKeyIssue(code: Int): Boolean = code in setOf(
        10001, 10002, 10005, 10006, 10007, 10008, 10009, 1001, 1007, 1009
    )
}
